"""Generate the option reference ``docs/options.md`` from the config dataclasses (Gate 10).

    python -m tomocpt.configManager.option_docs --out docs/options.md

One table per section and sub-section, fields in dataclass order: option (as used in the YAML and
in ``key=value``), level, type, default, help. Internal fields are left out. A test regenerates the
file and compares it with the committed one.
"""
import argparse
import sys
from dataclasses import fields, is_dataclass
from enum import Enum
from pathlib import Path
from typing import Any, List, Optional

from omegaconf import MISSING

from tomocpt.configManager.cli_options import CLI_FLAGS
from tomocpt.configManager.option_levels import (
    INTERNAL,
    SECTIONS,
    describe_type,
    option_help,
    option_level,
    subsection_help,
)

INTRO = """\
# TomoCPT options

<!-- Generated by `python -m tomocpt.configManager.option_docs --out docs/options.md` from
tomocpt/defaultConfigs/ and tomocpt/configManager/option_levels.py. Do not edit by hand. -->

Every setting of `tomocpt prepare_data` (section `prepData`), `tomocpt train` (`train`) and
`tomocpt predict` (`infer`), plus the paths in `shared`. What to change and when:
[tuning.md](tuning.md). Worked configs: [examples/](examples/).

**Setting an option.** In a YAML file given with `--config_file` (sections as below, sub-sections
nested), or on the command line as `key=value` after the flags, relative to the command's section
(`tomocpt train ... particles.class_head=softmax`). Only the **basic** options are also
`--flags`. Booleans are `true`/`false`; `none` clears an optional value.

**Levels.** `basic`: the everyday command-line flags and required values. `advanced`: every other
setting that changes training or prediction. `diagnostic`: settings that only add output for
inspection. `tomocpt init --level basic|advanced|diagnostic` writes a commented YAML with every
option up to that level. Settings left out of a YAML keep their defaults.

Required values are marked `???`. Fields that are not settings (unused, fixed by the code, or the
copies of the `shared` paths) are not listed.
"""

SECTION_NOTES = {
    "shared": "Paths used by several commands; `training_data_dir` and `chunks_dir` are also the flags "
              "`--training_data_dir` / `--chunks_dir` of `prepare_data` and `train`.",
    "prepData": "`tomocpt prepare_data`.",
    "train": "`tomocpt train`.",
    "infer": "`tomocpt predict`.",
}


def _default_text(value: Any) -> str:
    if value is MISSING or (isinstance(value, str) and value == "???"):
        return "`???` (required)"
    if value is None:
        return "`none`"
    if isinstance(value, bool):
        return "`true`" if value else "`false`"
    if isinstance(value, Enum):
        return f"`{value.value}`"
    if isinstance(value, (list, tuple)):
        return "`" + ",".join(str(v) for v in value) + "`"
    if isinstance(value, str) and value == "":
        return '`""`'
    return f"`{value}`"


def _cell(text: str) -> str:
    return " ".join(str(text).split()).replace("|", "\\|").replace("<", "&lt;").replace(">", "&gt;")


def _tables(section: str, obj: Any, prefix: str, title: str, note: str, out: List[str]) -> None:
    rows, subs = [], []
    for f in fields(type(obj)):
        value = getattr(obj, f.name)
        path = prefix + f.name
        if is_dataclass(value):
            subs.append((value, path, subsection_help(obj, f.name)))
            continue
        level = option_level(section, path)
        if level == INTERNAL:
            continue
        flag = " (flag)" if section != "shared" and path in CLI_FLAGS.get(section, ()) else ""
        rows.append(f"| `{section}.{path}` | {level}{flag} | {_cell(describe_type(f.type))} | "
                    f"{_default_text(value)} | {_cell(option_help(section, path))} |")
    if rows:
        out += ["", title, ""]
        if note:
            out += [_cell(note), ""]
        out += ["| Option | Level | Type | Default | Help |", "|---|---|---|---|---|"] + rows
    for value, path, sub_note in subs:
        _tables(section, value, path + ".", f"### {section}.{path}", sub_note, out)


def render_options_markdown() -> str:
    """The text of ``docs/options.md``."""
    from tomocpt.mainConfig import MainConfig

    m = MainConfig()
    out = [INTRO.rstrip("\n")]
    for section in SECTIONS:
        _tables(section, getattr(m, section), "", f"## {section}", SECTION_NOTES.get(section, ""), out)
    return "\n".join(out) + "\n"


def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(description="Write the TomoCPT option reference (Markdown).")
    ap.add_argument("--out", type=Path, default=None, help="Output file (default: stdout)")
    a = ap.parse_args(argv)
    text = render_options_markdown()
    if a.out is None:
        sys.stdout.write(text)
    else:
        a.out.parent.mkdir(parents=True, exist_ok=True)
        a.out.write_text(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
