"""G1-C1, G1-C2, G1-C3, G1-C8: numbers and pipelines locked to ``v2-gate-0-base`` goldens.

Goldens: ``tests/golden/gate1_*.{npz,json}``, generated by
``tests/golden/make_goldens_gate1.py`` in a worktree of ``v2-gate-0-base``.
"""

import json

import numpy as np
import pytest
import torch

from pathlib import Path
from utils.tiny import tiny_swin_kwargs

GOLDEN_DIR = Path(__file__).resolve().parents[1] / "golden"


@pytest.fixture(scope="module")
def goldens():
    return json.loads((GOLDEN_DIR / "gate1_goldens.json").read_text())


@pytest.fixture(scope="module")
def golden_spheres():
    with np.load(GOLDEN_DIR / "gate1_spheres.npz") as z:
        return {int(k[1:]): z[k] for k in z.files}


@pytest.mark.parametrize("radius", [5, 10, 17])
def test_G1_C1_gaussian_sphere_golden(radius, golden_spheres):
    from tomocpt.labels.helpers import generate_gaussian_sphere

    got = np.asarray(generate_gaussian_sphere(radius, 2 * radius + 1))
    want = golden_spheres[radius]
    assert got.shape == want.shape == (2 * radius + 1,) * 3
    np.testing.assert_allclose(got, want, rtol=0, atol=1e-7)


def test_G1_C2_loss_golden(tiny_global, golden_common, golden_spheres, goldens):
    from tomocpt.networks.pickingModel import BasePickingModel

    y_pred, y_true = golden_common.loss_inputs(golden_spheres)
    g = goldens["G1_C2_loss"]
    # the inputs are rebuilt, not stored: check they are the ones the golden was made from
    assert float(y_true.sum()) == pytest.approx(g["y_true_sum"], rel=1e-7)
    assert float(y_pred.astype(np.float64).sum()) == pytest.approx(g["y_pred_sum"], rel=1e-9)

    model = BasePickingModel(lr=1e-3, train_continue=None)
    with torch.no_grad():
        loss = model.loss(torch.from_numpy(y_pred), torch.from_numpy(y_true))
    assert loss.ndim == 0
    assert float(loss) == pytest.approx(g["value"], rel=1e-6, abs=0)


def test_G1_C3_tiny_forward_golden(golden_common):
    from tomocpt.networks.swinunetr import MySwinUNETR

    torch.manual_seed(0)
    net = MySwinUNETR(**tiny_swin_kwargs()).eval()
    with torch.no_grad():
        out = net(torch.from_numpy(golden_common.forward_input()))
    assert isinstance(out, tuple) and len(out) == 2
    logits, hidden4 = out
    with np.load(GOLDEN_DIR / "gate1_forward.npz") as z:
        want_logits, want_hidden = z["logits"], z["hidden4"]
    assert tuple(logits.shape) == want_logits.shape == (1, 1, 64, 64, 64)
    assert tuple(hidden4.shape) == want_hidden.shape == (1, 16 * 12, 2, 2, 2)
    np.testing.assert_allclose(logits.numpy(), want_logits, rtol=0, atol=1e-5)
    np.testing.assert_allclose(hidden4.numpy(), want_hidden, rtol=0, atol=1e-5)


def test_G1_C8_default_augmentation_pipeline_unchanged(golden_common, goldens):
    from tomocpt import constants
    from tomocpt.dataManager.dataloading import build_training_transforms
    from tomocpt.defaultConfigs.train_config import AugmentationConfig

    pipeline = build_training_transforms(AugmentationConfig())
    got = json.loads(json.dumps(golden_common.describe_transform(pipeline)))
    want = goldens["G1_C8_transforms"]

    got_types = [c["type"] for c in got["children"]]
    want_types = [c["type"] for c in want["children"]]
    assert got_types == want_types  # types and order
    for g, w in zip(got["children"], want["children"]):
        assert g == w, f"{g['type']} differs from v2-gate-0-base"
    assert got == want

    # contrast inversion: always on, at the fixed constant
    assert constants.CONTRAST_INVERSION_PROB == goldens["G1_C8_contrast_inversion_prob"] == 0.5
    (inv,) = [t for t in pipeline.transforms if type(t).__name__ == "RandomContrastInversion"]
    assert inv.probability == constants.CONTRAST_INVERSION_PROB
    assert want_types[-1] == "RandomContrastInversion"
